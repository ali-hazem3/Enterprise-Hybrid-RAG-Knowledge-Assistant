CREATE TABLE dbo.branches (
    branch_id   INT PRIMARY KEY,
    branch_name NVARCHAR(50) NOT NULL
);

CREATE TABLE dbo.plans (
    plan_id    INT PRIMARY KEY,
    plan_name  NVARCHAR(50) NOT NULL,
    price      DECIMAL(8,2) NOT NULL,
    billing    NVARCHAR(20) NOT NULL
);

CREATE TABLE dbo.members (
    member_id  INT PRIMARY KEY,
    full_name  NVARCHAR(100) NOT NULL,
    branch_id  INT NOT NULL REFERENCES dbo.branches(branch_id),
    plan_id    INT NOT NULL REFERENCES dbo.plans(plan_id),
    join_date  DATE NOT NULL
);

CREATE TABLE dbo.payments (
    payment_id INT IDENTITY(1,1) PRIMARY KEY,
    member_id  INT NOT NULL REFERENCES dbo.members(member_id),
    pay_date   DATE NOT NULL,
    amount     DECIMAL(8,2) NOT NULL
);

